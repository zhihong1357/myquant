/**
 * Standard normal and finite-sample Student-t distribution helpers.
 * Deterministic pure-TypeScript statistical primitives for MyQuant kernel.
 */

function erf(x: number): number {
  const sign = x >= 0 ? 1 : -1;
  const ax = Math.abs(x);
  const t = 1.0 / (1.0 + 0.3275911 * ax);
  const a1 = 0.254829592;
  const a2 = -0.284496736;
  const a3 = 1.421413741;
  const a4 = -1.453152027;
  const a5 = 1.061405429;
  const poly = (((((a5 * t + a4) * t) + a3) * t + a2) * t + a1) * t;
  const y = 1.0 - poly * Math.exp(-ax * ax);
  return sign * y;
}

export function normalCdf(z: number): number {
  if (!Number.isFinite(z)) {
    throw new Error('z must be finite');
  }
  return 0.5 * (1.0 + erf(z / Math.SQRT2));
}

export function twoSidedPValueFromZ(z: number): number {
  if (!Number.isFinite(z)) {
    throw new Error('z must be finite');
  }
  const tail = 1.0 - normalCdf(Math.abs(z));
  return Math.min(1.0, Math.max(0.0, 2.0 * tail));
}

/**
 * Lanczos approximation for ln(Gamma(z)), accurate to ~1e-13 for z > 0.
 */
export function logGamma(z: number): number {
  if (!Number.isFinite(z) || z <= 0) {
    throw new Error('logGamma requires finite z > 0');
  }
  const g = 7;
  const p = [
    0.99999999999980993,
    676.5203681218851,
    -1259.1392167224028,
    771.32342877765313,
    -176.61502916214059,
    12.507343278686905,
    -0.13857109526572012,
    9.9843695780195716e-6,
    1.5056327351493116e-7,
  ];
  if (z < 0.5) {
    return Math.log(Math.PI / Math.sin(Math.PI * z)) - logGamma(1 - z);
  }
  const zm = z - 1;
  let x = p[0];
  for (let i = 1; i < g + 2; i++) {
    x += p[i] / (zm + i);
  }
  const t = zm + g + 0.5;
  return 0.5 * Math.log(2 * Math.PI) + (zm + 0.5) * Math.log(t) - t + Math.log(x);
}

function betacf(a: number, b: number, x: number): number {
  const MAXIT = 200;
  const EPS = 3e-12;
  const FPMIN = 1e-30;
  const qab = a + b;
  const qap = a + 1.0;
  const qam = a - 1.0;
  let c = 1.0;
  let d = 1.0 - (qab * x) / qap;
  if (Math.abs(d) < FPMIN) d = FPMIN;
  d = 1.0 / d;
  let h = d;

  for (let m = 1; m <= MAXIT; m++) {
    const m2 = 2 * m;
    let aa = (m * (b - m) * x) / ((qam + m2) * (a + m2));
    d = 1.0 + aa * d;
    if (Math.abs(d) < FPMIN) d = FPMIN;
    c = 1.0 + aa / c;
    if (Math.abs(c) < FPMIN) c = FPMIN;
    d = 1.0 / d;
    h *= d * c;

    aa = (-(a + m) * (qab + m) * x) / ((a + m2) * (qap + m2));
    d = 1.0 + aa * d;
    if (Math.abs(d) < FPMIN) d = FPMIN;
    c = 1.0 + aa / c;
    if (Math.abs(c) < FPMIN) c = FPMIN;
    d = 1.0 / d;
    const del = d * c;
    h *= del;
    if (Math.abs(del - 1.0) < EPS) {
      break;
    }
  }
  return h;
}

/**
 * Regularized incomplete beta function I_x(a, b) via Lentz continued fraction.
 */
export function regIncompleteBeta(x: number, a: number, b: number): number {
  if (x <= 0) return 0;
  if (x >= 1) return 1;
  const bt = Math.exp(
    logGamma(a + b) - logGamma(a) - logGamma(b) + a * Math.log(x) + b * Math.log(1 - x),
  );
  if (x < (a + 1) / (a + b + 2)) {
    return (bt * betacf(a, b, x)) / a;
  }
  return 1.0 - (bt * betacf(b, a, 1 - x)) / b;
}

/**
 * Exact finite-sample two-sided Student-t p-value for statistic t with df degrees of freedom.
 * Eliminates asymptotic normal-tail understatement on small samples / event studies.
 */
export function twoSidedPValueFromT(t: number, df: number): number {
  if (!Number.isFinite(t)) {
    throw new Error('t must be finite');
  }
  if (!Number.isFinite(df) || df <= 0) {
    throw new Error('df must be positive');
  }
  if (t === 0) return 1.0;
  if (df > 1e6) return twoSidedPValueFromZ(t);
  const x = df / (df + t * t);
  const p = regIncompleteBeta(x, df / 2, 0.5);
  return Math.min(1.0, Math.max(0.0, p));
}

/**
 * Peter John Acklam's rational approximation for the inverse standard normal CDF.
 * Relative error is less than 1.15e-9 across (0, 1).
 */
export function normalPpf(p: number): number {
  if (!Number.isFinite(p) || p <= 0 || p >= 1) {
    throw new Error('p must lie strictly between 0 and 1');
  }

  const a = [
    -3.969683028665376e1,
    2.209460984245205e2,
    -2.759285104469687e2,
    1.383577518672690e2,
    -3.066479806614716e1,
    2.506628277459239e0,
  ];
  const b = [
    -5.447609879822406e1,
    1.615858368580409e2,
    -1.556989798598866e2,
    6.680131188771972e1,
    -1.328068155288572e1,
  ];
  const c = [
    -7.784894002430293e-3,
    -3.223964580411365e-1,
    -2.400758277161838e0,
    -2.549732539343734e0,
    4.374664141464968e0,
    2.938163982698783e0,
  ];
  const d = [
    7.784695709041462e-3,
    3.224671290700398e-1,
    2.445134137142996e0,
    3.754408661907416e0,
  ];

  const pLow = 0.02425;
  const pHigh = 1 - pLow;

  if (p < pLow) {
    const q = Math.sqrt(-2 * Math.log(p));
    return (
      (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) /
      ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1)
    );
  }
  if (p <= pHigh) {
    const q = p - 0.5;
    const r = q * q;
    return (
      ((((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * q) /
      (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1)
    );
  }
  const q = Math.sqrt(-2 * Math.log(1 - p));
  return -(
    (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) /
    ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1)
  );
}
