"""Market graph and edge registry contracts, queries and rendering.

The graph records which transmission edges have been tested, what the
evidence was, and which directed pairs remain untested. An edge is a
tested (or preregistered, or descriptive) transmission hypothesis, not a
causal claim: the registry records "what was measured", never "how the
market works". A directed pair with no edge is an untested candidate, not
evidence of anything.

The registry file (``research/graph/registry.json``) is generated by
``research/graph/build_graph.py`` from the studies' trial ledgers and
preregistrations. Never edit the generated registry by hand; re-run the
builder after a new study lands.
"""

from __future__ import annotations

import hashlib
from datetime import datetime
from enum import StrEnum
from pathlib import Path
from typing import Annotated, Any

from pydantic import Field, model_validator

from myquant.canonical import canonical_json
from myquant.contracts import StrictContract

REGISTRY_SCHEMA_VERSION = 1


class EdgeStatus(StrEnum):
    """Evidence status of a registered edge.

    SUPPORTED/REJECTED are verdicts from a completed test family.
    PENDING is preregistered but untested (no trial has run). DESCRIPTIVE
    is a descriptive check only: it was never in a test family, carries no
    verdict, and must never be cited as test evidence.
    """

    SUPPORTED = "supported"
    REJECTED = "rejected"
    PENDING = "pending"
    DESCRIPTIVE = "descriptive"


class CostGateVerdict(StrEnum):
    """Outcome of a trial's economic cost gate."""

    PASS = "pass"
    FAIL = "fail"
    INFORMATIONAL = "informational"


class CostGateRecord(StrictContract):
    """Trial-level economic cost gate, attached to the primary edge only."""

    verdict: CostGateVerdict
    net_daily_edge: Annotated[float, Field(allow_inf_nan=False)] | None
    gross_daily_edge: Annotated[float, Field(allow_inf_nan=False)]
    bootstrap_p_value: Annotated[float, Field(ge=0.0, le=1.0)] | None
    ci_lower: Annotated[float, Field(allow_inf_nan=False)] | None
    ci_upper: Annotated[float, Field(allow_inf_nan=False)] | None
    days: Annotated[int, Field(ge=0)]
    note: Annotated[str, Field(min_length=1)]


class SampleRecord(StrictContract):
    """Sample window behind one edge's test."""

    first: datetime
    last: datetime
    panel_rows: Annotated[int, Field(ge=1)]
    observations: Annotated[int, Field(ge=1)]


class ForwardSampleRecord(StrictContract):
    """Forward-sample accumulation for a PENDING edge (counts only)."""

    minimum_lowvol_rows: Annotated[int, Field(ge=1)]
    observed_lowvol_rows: Annotated[int, Field(ge=0)]
    forward_rows: Annotated[int, Field(ge=0)]
    checked_at: datetime
    window_start: datetime
    window_end: datetime
    ready: bool


class EdgeRecord(StrictContract):
    """One registered transmission edge (one test configuration).

    Edge records are versioned and immutable: a correction produces a new
    version, mirroring the hypothesis registry. All statistics come from
    the trial ledger, never typed in by hand.
    """

    edge_id: Annotated[str, Field(pattern=r"^E[0-9]{4}$")]
    version: Annotated[int, Field(ge=1)] = 1
    status: EdgeStatus
    source_instrument: Annotated[str, Field(min_length=1)]
    target_instrument: Annotated[str, Field(min_length=1)]
    frequency: Annotated[str, Field(pattern=r"^(daily|hourly|weekly)$")]
    lag_steps: Annotated[int, Field(ge=1)]
    condition: str | None
    method: Annotated[str, Field(min_length=1)]
    common_factor_control: str | None
    data_sources: tuple[str, ...] = ()
    hypothesis_id: Annotated[str, Field(min_length=1)]
    hypothesis_version: Annotated[int, Field(ge=1)]
    trial_id: str | None
    preregistration_fingerprint: Annotated[str, Field(min_length=1)]
    trial_record_hash: str | None
    report_path: Annotated[str, Field(min_length=1)]
    ledger_path: Annotated[str, Field(min_length=1)]
    ledger_test_key: str | None
    coefficient: Annotated[float, Field(allow_inf_nan=False)] | None
    standard_error: Annotated[float, Field(allow_inf_nan=False)] | None
    t_statistic: Annotated[float, Field(allow_inf_nan=False)] | None
    p_value: Annotated[float, Field(ge=0.0, le=1.0)] | None
    holm_adjusted_p_value: Annotated[float, Field(ge=0.0, le=1.0)] | None
    partial_r_squared: Annotated[float, Field(ge=0.0, le=1.0)] | None
    incremental_r_squared: Annotated[float, Field(allow_inf_nan=False)] | None
    observations: Annotated[int, Field(ge=1)] | None
    sample: SampleRecord | None
    holdout_oos_incremental_r_squared: (
        Annotated[float, Field(allow_inf_nan=False)] | None
    )
    holdout_oos_note: str | None
    cost_gate: CostGateRecord | None
    cost_gate_note: str | None
    forward_sample: ForwardSampleRecord | None
    verdict_summary: Annotated[str, Field(min_length=1)]
    notes: tuple[str, ...] = ()

    @model_validator(mode="after")
    def validate_status_shape(self) -> EdgeRecord:
        if self.source_instrument == self.target_instrument:
            raise ValueError("an edge cannot point at its own instrument")
        tested = self.status in {EdgeStatus.SUPPORTED, EdgeStatus.REJECTED}
        if tested:
            if self.trial_id is None or self.trial_record_hash is None:
                raise ValueError("a tested edge needs a trial id and record hash")
            if (
                self.coefficient is None
                or self.p_value is None
                or self.holm_adjusted_p_value is None
                or self.partial_r_squared is None
                or self.observations is None
                or self.sample is None
            ):
                raise ValueError("a tested edge needs full test statistics")
            if self.forward_sample is not None:
                raise ValueError("a tested edge must not carry a forward sample")
        if self.status is EdgeStatus.PENDING:
            if self.trial_id is not None or self.trial_record_hash is not None:
                raise ValueError("a pending edge has no trial yet")
            if self.forward_sample is None:
                raise ValueError("a pending edge needs its forward sample record")
            if (
                self.coefficient is not None
                or self.p_value is not None
                or self.holm_adjusted_p_value is not None
            ):
                raise ValueError("a pending edge has no test statistics yet")
        if self.status is EdgeStatus.DESCRIPTIVE:
            if self.holm_adjusted_p_value is not None:
                raise ValueError(
                    "a descriptive edge was never in a test family and "
                    "has no Holm-adjusted p-value"
                )
        return self


class NodeRecord(StrictContract):
    """One instrument node in the graph."""

    instrument_id: Annotated[str, Field(min_length=1)]
    short_label: Annotated[str, Field(min_length=1)]
    name: Annotated[str, Field(min_length=1)]
    asset_class: Annotated[str, Field(min_length=1)]
    instrument_type: Annotated[str, Field(min_length=1)]
    calendar_id: Annotated[str, Field(min_length=1)]
    studies: tuple[str, ...] = ()


class CandidateRecord(StrictContract):
    """One directed pair with no tested or pending edge.

    A candidate is an untested pair, not evidence of any relationship.
    ``related_descriptive`` names a descriptive check on the pair, if one
    exists; it does not promote the pair to tested.
    """

    source_instrument: Annotated[str, Field(min_length=1)]
    target_instrument: Annotated[str, Field(min_length=1)]
    note: Annotated[str, Field(min_length=1)]
    related_descriptive: str | None = None

    @model_validator(mode="after")
    def validate_pair(self) -> CandidateRecord:
        if self.source_instrument == self.target_instrument:
            raise ValueError("a candidate cannot point at its own instrument")
        return self


class ProvenanceRecord(StrictContract):
    """Where one study's edge records came from."""

    study: Annotated[str, Field(min_length=1)]
    trial_id: str | None
    ledger_path: Annotated[str, Field(min_length=1)]
    trial_record_hash: str | None
    registration_path: Annotated[str, Field(min_length=1)]
    preregistration_fingerprint: Annotated[str, Field(min_length=1)]


def compute_content_hash(
    *,
    schema_version: int,
    nodes: tuple[NodeRecord, ...] | list[NodeRecord],
    edges: tuple[EdgeRecord, ...] | list[EdgeRecord],
    candidates: tuple[CandidateRecord, ...] | list[CandidateRecord],
    provenance: tuple[ProvenanceRecord, ...] | list[ProvenanceRecord],
) -> str:
    """SHA-256 over the canonical JSON of the registry contents."""
    payload: dict[str, Any] = {
        "schema_version": schema_version,
        "nodes": [node.model_dump(mode="json") for node in nodes],
        "edges": [edge.model_dump(mode="json") for edge in edges],
        "candidates": [candidate.model_dump(mode="json") for candidate in candidates],
        "provenance": [entry.model_dump(mode="json") for entry in provenance],
    }
    return hashlib.sha256(canonical_json(payload)).hexdigest()


class GraphRegistry(StrictContract):
    """The full market graph: nodes, edges, candidates and provenance."""

    schema_version: Annotated[int, Field(ge=1)] = REGISTRY_SCHEMA_VERSION
    nodes: tuple[NodeRecord, ...]
    edges: tuple[EdgeRecord, ...]
    candidates: tuple[CandidateRecord, ...]
    provenance: tuple[ProvenanceRecord, ...]
    content_hash: Annotated[str, Field(pattern=r"^[0-9a-f]{64}$")]

    @model_validator(mode="after")
    def validate_graph(self) -> GraphRegistry:
        node_ids = {node.instrument_id for node in self.nodes}
        if len(node_ids) != len(self.nodes):
            raise ValueError("node instrument ids must be unique")
        edge_ids = [edge.edge_id for edge in self.edges]
        if len(set(edge_ids)) != len(edge_ids):
            raise ValueError("edge ids must be unique")
        for edge in self.edges:
            if edge.source_instrument not in node_ids:
                raise ValueError(f"edge {edge.edge_id} has an unknown source node")
            if edge.target_instrument not in node_ids:
                raise ValueError(f"edge {edge.edge_id} has an unknown target node")
        covered = {
            (edge.source_instrument, edge.target_instrument)
            for edge in self.edges
            if edge.status
            in {EdgeStatus.SUPPORTED, EdgeStatus.REJECTED, EdgeStatus.PENDING}
        }
        seen_candidates: set[tuple[str, str]] = set()
        for candidate in self.candidates:
            pair = (candidate.source_instrument, candidate.target_instrument)
            if pair[0] not in node_ids or pair[1] not in node_ids:
                raise ValueError("a candidate names an unknown node")
            if pair in covered:
                raise ValueError("a candidate duplicates a tested or pending pair")
            if pair in seen_candidates:
                raise ValueError("candidate pairs must be unique")
            seen_candidates.add(pair)
        expected = compute_content_hash(
            schema_version=self.schema_version,
            nodes=self.nodes,
            edges=self.edges,
            candidates=self.candidates,
            provenance=self.provenance,
        )
        if expected != self.content_hash:
            raise ValueError("registry content hash mismatch")
        return self


def build_candidates(
    nodes: tuple[NodeRecord, ...],
    edges: tuple[EdgeRecord, ...],
    *,
    descriptive_notes: dict[tuple[str, str], str] | None = None,
) -> tuple[CandidateRecord, ...]:
    """All directed pairs with no tested or pending edge.

    Pairs are emitted in deterministic order (nodes sorted by instrument
    id, sources outer, targets inner). Descriptive-only pairs stay
    candidates: a descriptive check is not a test.
    """
    covered = {
        (edge.source_instrument, edge.target_instrument)
        for edge in edges
        if edge.status
        in {EdgeStatus.SUPPORTED, EdgeStatus.REJECTED, EdgeStatus.PENDING}
    }
    notes = descriptive_notes or {}
    ordered = sorted(node.instrument_id for node in nodes)
    candidates: list[CandidateRecord] = []
    for source in ordered:
        for target in ordered:
            if source == target or (source, target) in covered:
                continue
            candidates.append(
                CandidateRecord(
                    source_instrument=source,
                    target_instrument=target,
                    note=(
                        "No test registered for this pair; it is an "
                        "untested candidate, not evidence of any relationship."
                    ),
                    related_descriptive=notes.get((source, target)),
                )
            )
    return tuple(candidates)


class MarketGraph:
    """Query interface over a validated graph registry."""

    def __init__(self, registry: GraphRegistry) -> None:
        self._registry = registry
        self._nodes = {node.instrument_id: node for node in registry.nodes}

    @classmethod
    def from_file(cls, path: str | Path) -> MarketGraph:
        return cls(GraphRegistry.model_validate_json(Path(path).read_text()))

    @property
    def registry(self) -> GraphRegistry:
        return self._registry

    @property
    def nodes(self) -> tuple[NodeRecord, ...]:
        return self._registry.nodes

    @property
    def edges(self) -> tuple[EdgeRecord, ...]:
        return self._registry.edges

    @property
    def candidates(self) -> tuple[CandidateRecord, ...]:
        return self._registry.candidates

    def node(self, instrument_id: str) -> NodeRecord:
        return self._nodes[instrument_id]

    def edges_by(
        self,
        *,
        source: str | None = None,
        target: str | None = None,
        status: EdgeStatus | None = None,
        frequency: str | None = None,
    ) -> tuple[EdgeRecord, ...]:
        """Edges filtered by source, target, status and/or frequency."""
        return tuple(
            edge
            for edge in self._registry.edges
            if (source is None or edge.source_instrument == source)
            and (target is None or edge.target_instrument == target)
            and (status is None or edge.status == status)
            and (frequency is None or edge.frequency == frequency)
        )

    def edge_between(self, source: str, target: str) -> tuple[EdgeRecord, ...]:
        """All registered edges on one directed pair, in registry order."""
        return self.edges_by(source=source, target=target)

    def untested_candidates(
        self,
        *,
        source: str | None = None,
        target: str | None = None,
    ) -> tuple[CandidateRecord, ...]:
        """Untested candidate pairs, optionally filtered by endpoint."""
        return tuple(
            candidate
            for candidate in self._registry.candidates
            if (source is None or candidate.source_instrument == source)
            and (target is None or candidate.target_instrument == target)
        )

    def tested_pairs(self) -> set[tuple[str, str]]:
        """Directed pairs with at least one tested or pending edge."""
        return {
            (edge.source_instrument, edge.target_instrument)
            for edge in self._registry.edges
            if edge.status
            in {EdgeStatus.SUPPORTED, EdgeStatus.REJECTED, EdgeStatus.PENDING}
        }

    def summary(self) -> dict[str, int]:
        """Counts of nodes, edges by status, and untested candidates."""
        counts: dict[str, int] = {
            "nodes": len(self._registry.nodes),
            "edges": len(self._registry.edges),
            "candidates": len(self._registry.candidates),
        }
        for status in EdgeStatus:
            counts[f"edges_{status.value}"] = sum(
                1 for edge in self._registry.edges if edge.status == status
            )
        return counts


def _format_number(value: float | None, *, decimals: int = 4) -> str:
    if value is None:
        return "n/a"
    return f"{value:+.{decimals}f}"


def render_mermaid(registry: GraphRegistry) -> str:
    """Render the graph as a Mermaid flowchart (GitHub-native rendering).

    Tested edges are solid arrows, pending edges are dashed, descriptive
    edges are dashed and labelled DESCRIPTIVE. Nodes are grouped by asset
    class. Labels carry the edge id, frequency, coefficient, Holm-adjusted
    p-value (tested edges) and status — enough to read the graph without
    opening the registry.
    """
    labels = {node.instrument_id: node.short_label for node in registry.nodes}
    groups: dict[str, list[NodeRecord]] = {}
    for node in registry.nodes:
        groups.setdefault(node.asset_class, []).append(node)
    group_titles = {
        "crypto": "Crypto perpetuals",
        "volatility": "Volatility indices",
        "index": "Equity indices",
        "rates": "Rates",
        "credit": "Credit",
    }
    lines = ["flowchart LR"]
    for asset_class in sorted(groups):
        title = group_titles.get(asset_class, asset_class.title())
        lines.append(f"    subgraph {asset_class}[{title}]")
        for node in sorted(groups[asset_class], key=lambda n: n.short_label):
            lines.append(f"        {node.short_label}[{node.short_label}]")
        lines.append("    end")
    for edge in registry.edges:
        source = labels[edge.source_instrument]
        target = labels[edge.target_instrument]
        if edge.status is EdgeStatus.PENDING:
            assert edge.forward_sample is not None
            observed = edge.forward_sample.observed_lowvol_rows
            minimum = edge.forward_sample.minimum_lowvol_rows
            label = (
                f"{edge.edge_id} {edge.frequency} low-vol, "
                f"{edge.hypothesis_id} PENDING, {observed}/{minimum}"
            )
            lines.append(f"    {source} -.->|{label}| {target}")
        elif edge.status is EdgeStatus.DESCRIPTIVE:
            label = (
                f"{edge.edge_id} {edge.frequency}, "
                f"coef {_format_number(edge.coefficient)}, "
                "DESCRIPTIVE, no verdict"
            )
            lines.append(f"    {source} -.->|{label}| {target}")
        else:
            holm = (
                f"{edge.holm_adjusted_p_value:.3f}"
                if edge.holm_adjusted_p_value is not None
                else "n/a"
            )
            label = (
                f"{edge.edge_id} {edge.frequency}, "
                f"coef {_format_number(edge.coefficient)}, "
                f"Holm p {holm}, {edge.status.value.upper()}"
            )
            lines.append(f"    {source} -->|{label}| {target}")
    return "\n".join(lines) + "\n"
