"""Forward shadow evaluation of prediction streams (Stage 5b).

A shadow evaluation scores a stream of predictions (:class:`Prediction`
from the Stage 5a contract) as their target windows close, against
realized outcomes supplied by a caller-provided outcome provider.
Scoring is forward-only and append-only in spirit: a prediction is
scored exactly once, at or after its ``target_time``, and the scored
ledger is never rewritten.

Scoring discipline (hard rules, all enforced here):

- A prediction is scored only when ``scored_at`` is strictly after
  its ``target_time``: the outcome over [event_time, target_time]
  is not knowable before the window closes. A prediction whose
  window has not closed is recorded as unscored
  (``not_yet_due``), never estimated from partial information.
- If the outcome provider returns ``None`` for a due prediction,
  the prediction is recorded as unscored (``outcome_missing``):
  a missing outcome is missing data, not a zero error.
- An optional fit window ``[start, end)`` declares the in-sample
  period. Predictions with ``event_time`` inside it are refused
  scoring (``in_fit_window``) so in-sample scores cannot masquerade
  as out-of-sample ones.

Metrics are computed per target type, over the scored predictions
only. Formulas (``e = predicted - outcome``):

- All targets: MSE = mean(e^2), MAE = mean(|e|), bias = mean(e).
- ``log_return`` additionally: Pearson correlation between predicted
  and outcome (``None`` when undefined), and hit rate = fraction of
  scored predictions whose sign agrees with the outcome's sign
  (sign(0) = 0, so a flat prediction matching a flat outcome counts).
- ``direction`` additionally: accuracy = fraction with
  predicted == outcome, and confusion counts over non-zero pairs:
  TP (pred +1, outcome +1), FP (pred +1, outcome -1), TN (pred -1,
  outcome -1), FN (pred -1, outcome +1). Predictions or outcomes of
  exactly 0 are counted separately (``zeros_predicted``,
  ``zeros_outcome``) and do not enter TP/FP/TN/FN.

Every score is reported against baselines. The zero baseline
(predicted value 0 for every prediction; for ``direction`` the
constant 0) is always computed on the same scored set. Named
baselines (e.g. the lag-return fixture, generated by the caller
with :func:`make_lag_return_fixture`) are scored with the same
provider and the same discipline, matched to the stream by
(instrument, event_time, target); a baseline's skill is computed
only over the matched scored pairs, so the comparison is
like-for-like. Skill is ``1 - MSE / MSE_baseline``; a negative
skill means worse than the baseline. Skill is ``None`` when
undefined (no matched baseline scores, or a zero baseline MSE).

The scorer is venue-agnostic: outcomes come from the provider, a
plain callable taking a :class:`Prediction` and returning the
realized value or ``None``. The provider is only queried for
predictions that are due and outside the fit window.

Determinism: ``scored_at`` and the fit window are inputs, never
read from the clock, so the same inputs always produce the same
evaluation, and :func:`shadow_ledger_json` is byte-identical on
re-runs.
"""

from __future__ import annotations

import json
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime
from math import isfinite

import numpy as np
from pydantic import Field

from myquant.contracts import StrictContract, require_utc
from myquant.portfolio.predictions import Prediction, PredictionTarget

#: Reasons a prediction may be left unscored.
NOT_YET_DUE = "not_yet_due"
OUTCOME_MISSING = "outcome_missing"
IN_FIT_WINDOW = "in_fit_window"

OutcomeProvider = Callable[[Prediction], float | None]


class ScoredPrediction(StrictContract):
    """One prediction and its scoring outcome (or the reason it was not scored)."""

    prediction_id: str
    instrument_id: str
    target: PredictionTarget
    event_time: datetime
    target_time: datetime
    scored_at: datetime
    predicted: float = Field(allow_inf_nan=False)
    outcome: float | None = Field(default=None, allow_inf_nan=False)
    error: float | None = Field(default=None, allow_inf_nan=False)
    scored: bool
    unscored_reason: str | None = Field(default=None)


class ConfusionCounts(StrictContract):
    """Confusion counts for direction predictions, over non-zero pairs only."""

    true_positive: int = Field(ge=0)
    false_positive: int = Field(ge=0)
    true_negative: int = Field(ge=0)
    false_negative: int = Field(ge=0)
    zeros_predicted: int = Field(ge=0)
    zeros_outcome: int = Field(ge=0)


class BaselineSkill(StrictContract):
    """One named baseline's skill against the stream, on matched pairs."""

    name: str
    matched_pairs: int = Field(ge=0)
    baseline_mse: float | None = Field(default=None, ge=0, allow_inf_nan=False)
    skill: float | None = Field(default=None, allow_inf_nan=False)


class TargetMetrics(StrictContract):
    """Aggregate scores for one target type, over the scored predictions."""

    target: PredictionTarget
    n_scored: int = Field(ge=1)
    mse: float = Field(ge=0, allow_inf_nan=False)
    mae: float = Field(ge=0, allow_inf_nan=False)
    bias: float = Field(allow_inf_nan=False)
    correlation: float | None = Field(default=None, allow_inf_nan=False)
    hit_rate: float | None = Field(default=None, ge=0, le=1, allow_inf_nan=False)
    accuracy: float | None = Field(default=None, ge=0, le=1, allow_inf_nan=False)
    confusion: ConfusionCounts | None = Field(default=None)
    zero_baseline_mse: float = Field(ge=0, allow_inf_nan=False)
    skill_vs_zero: float | None = Field(default=None, allow_inf_nan=False)
    baselines: tuple[BaselineSkill, ...] = Field(default=())


class ShadowEvaluation(StrictContract):
    """The complete result of one shadow scoring run."""

    scored_at: datetime
    fit_window: tuple[datetime, datetime] | None = Field(default=None)
    predictions: tuple[ScoredPrediction, ...]
    metrics: tuple[TargetMetrics, ...]
    n_total: int = Field(ge=0)
    n_scored: int = Field(ge=0)
    n_unscored: int = Field(ge=0)
    unscored_counts: dict[str, int] = Field(default_factory=dict)


@dataclass(frozen=True)
class _ScoredArrays:
    predicted: np.ndarray
    outcome: np.ndarray
    error: np.ndarray


def _skill(mse: float, baseline_mse: float | None) -> float | None:
    """Skill = 1 - MSE / MSE_baseline; None when the ratio is undefined."""
    if baseline_mse is None or baseline_mse == 0.0:
        return None
    return float(1.0 - mse / baseline_mse)


def _pearson(x: np.ndarray, y: np.ndarray) -> float | None:
    """Pearson correlation; None when undefined (n < 2 or zero variance)."""
    if x.size < 2:
        return None
    x_centered = x - float(np.mean(x))
    y_centered = y - float(np.mean(y))
    x_ss = float(x_centered @ x_centered)
    y_ss = float(y_centered @ y_centered)
    if x_ss == 0.0 or y_ss == 0.0:
        return None
    return float((x_centered @ y_centered) / np.sqrt(x_ss * y_ss))


def _metrics_for_target(
    target: PredictionTarget,
    arrays: _ScoredArrays,
    *,
    baselines: tuple[BaselineSkill, ...] = (),
) -> TargetMetrics:
    """Aggregate metrics for one target group (scored predictions only)."""
    predicted, outcome, error = arrays.predicted, arrays.outcome, arrays.error
    mse = float(np.mean(error**2))
    mae = float(np.mean(np.abs(error)))
    bias = float(np.mean(error))
    zero_mse = float(np.mean(outcome**2))
    correlation: float | None = None
    hit_rate: float | None = None
    accuracy: float | None = None
    confusion: ConfusionCounts | None = None
    if target is PredictionTarget.LOG_RETURN:
        correlation = _pearson(predicted, outcome)
        hit_rate = float(np.mean(np.sign(predicted) == np.sign(outcome)))
    elif target is PredictionTarget.DIRECTION:
        accuracy = float(np.mean(predicted == outcome))
        nonzero = (predicted != 0.0) & (outcome != 0.0)
        pred_nz = predicted[nonzero]
        out_nz = outcome[nonzero]
        confusion = ConfusionCounts(
            true_positive=int(np.count_nonzero((pred_nz == 1.0) & (out_nz == 1.0))),
            false_positive=int(np.count_nonzero((pred_nz == 1.0) & (out_nz == -1.0))),
            true_negative=int(np.count_nonzero((pred_nz == -1.0) & (out_nz == -1.0))),
            false_negative=int(np.count_nonzero((pred_nz == -1.0) & (out_nz == 1.0))),
            zeros_predicted=int(np.count_nonzero(predicted == 0.0)),
            zeros_outcome=int(np.count_nonzero(outcome == 0.0)),
        )
    return TargetMetrics(
        target=target,
        n_scored=int(predicted.size),
        mse=mse,
        mae=mae,
        bias=bias,
        correlation=correlation,
        hit_rate=hit_rate,
        accuracy=accuracy,
        confusion=confusion,
        zero_baseline_mse=zero_mse,
        skill_vs_zero=_skill(mse, zero_mse),
        baselines=baselines,
    )


def _record(
    prediction: Prediction,
    scored_at: datetime,
    *,
    outcome: float | None,
    error: float | None,
    scored: bool,
    reason: str | None,
) -> ScoredPrediction:
    """Build a ledger record for one prediction (fields spelled out for mypy)."""
    return ScoredPrediction(
        prediction_id=prediction.prediction_id,
        instrument_id=prediction.instrument_id,
        target=prediction.target,
        event_time=prediction.event_time,
        target_time=prediction.target_time,
        scored_at=scored_at,
        predicted=prediction.value,
        outcome=outcome,
        error=error,
        scored=scored,
        unscored_reason=reason,
    )


def _score_one(
    prediction: Prediction,
    outcome_provider: OutcomeProvider,
    *,
    scored_at: datetime,
    fit_window: tuple[datetime, datetime] | None,
) -> ScoredPrediction:
    """Score one prediction, enforcing the scoring discipline."""
    if fit_window is not None and fit_window[0] <= prediction.event_time < fit_window[1]:
        return _record(
            prediction, scored_at, outcome=None, error=None, scored=False,
            reason=IN_FIT_WINDOW,
        )
    if scored_at <= prediction.target_time:
        return _record(
            prediction, scored_at, outcome=None, error=None, scored=False,
            reason=NOT_YET_DUE,
        )
    outcome = outcome_provider(prediction)
    if outcome is None or not isfinite(outcome):
        return _record(
            prediction, scored_at, outcome=None, error=None, scored=False,
            reason=OUTCOME_MISSING,
        )
    return _record(
        prediction,
        scored_at,
        outcome=float(outcome),
        error=float(prediction.value - outcome),
        scored=True,
        reason=None,
    )


def _score_baselines(
    scored_by_key: Mapping[tuple[str, datetime, PredictionTarget], ScoredPrediction],
    baselines: Mapping[str, Sequence[Prediction]],
    outcome_provider: OutcomeProvider,
    *,
    scored_at: datetime,
    fit_window: tuple[datetime, datetime] | None,
) -> dict[PredictionTarget, tuple[BaselineSkill, ...]]:
    """Score each named baseline and match it to the stream's scored set.

    Returns, per target, one :class:`BaselineSkill` per named
    baseline. A pair matches when the baseline prediction and a
    stream prediction share (instrument, event_time, target) and
    both are scored. Skill is computed on the matched pairs only,
    using the stream's MSE on those same pairs, so the comparison
    is like-for-like.
    """
    sums: dict[PredictionTarget, dict[str, tuple[int, float, float]]] = {}
    for name in sorted(baselines):
        for baseline_prediction in baselines[name]:
            key = (
                baseline_prediction.instrument_id,
                baseline_prediction.event_time,
                baseline_prediction.target,
            )
            stream_record = scored_by_key.get(key)
            if stream_record is None:
                continue
            scored_baseline = _score_one(
                baseline_prediction,
                outcome_provider,
                scored_at=scored_at,
                fit_window=fit_window,
            )
            if not scored_baseline.scored:
                continue
            assert scored_baseline.error is not None
            assert stream_record.error is not None
            per_target = sums.setdefault(baseline_prediction.target, {})
            matched, baseline_sse, stream_sse = per_target.get(name, (0, 0.0, 0.0))
            per_target[name] = (
                matched + 1,
                baseline_sse + scored_baseline.error**2,
                stream_sse + stream_record.error**2,
            )
    results: dict[PredictionTarget, tuple[BaselineSkill, ...]] = {}
    for target, per_target in sums.items():
        entries: list[BaselineSkill] = []
        for name in sorted(per_target):
            matched, baseline_sse, stream_sse = per_target[name]
            baseline_mse = baseline_sse / matched
            stream_mse = stream_sse / matched
            entries.append(
                BaselineSkill(
                    name=name,
                    matched_pairs=matched,
                    baseline_mse=baseline_mse,
                    skill=_skill(stream_mse, baseline_mse),
                )
            )
        results[target] = tuple(entries)
    # Baselines with no matched pairs at all are reported with zero
    # pairs and undefined skill, so a missing baseline is visible
    # rather than silently absent.
    for target in {t for _, _, t in scored_by_key}:
        existing = results.setdefault(target, ())
        known = {entry.name for entry in existing}
        missing = tuple(
            BaselineSkill(name=name, matched_pairs=0, baseline_mse=None, skill=None)
            for name in sorted(baselines)
            if name not in known
        )
        if missing:
            results[target] = tuple(sorted((*existing, *missing), key=lambda e: e.name))
    return results


def score_predictions(
    predictions: Sequence[Prediction],
    outcome_provider: OutcomeProvider,
    *,
    scored_at: datetime,
    fit_window: tuple[datetime, datetime] | None = None,
    baselines: Mapping[str, Sequence[Prediction]] | None = None,
) -> ShadowEvaluation:
    """Score a prediction stream forward-only against realized outcomes.

    ``scored_at`` is the scoring time: only predictions whose
    ``target_time`` strictly precedes it are scored. ``fit_window``
    is a half-open [start, end) in-sample interval whose predictions
    are refused scoring. ``baselines`` maps a baseline name to its
    predictions; each is scored with the same provider and
    discipline and matched to the stream by (instrument, event_time,
    target) for a like-for-like skill comparison.
    """
    scored_time = require_utc(scored_at)
    window: tuple[datetime, datetime] | None = None
    if fit_window is not None:
        start, end = require_utc(fit_window[0]), require_utc(fit_window[1])
        if end <= start:
            raise ValueError("fit_window end must be after its start")
        window = (start, end)
    ordered = sorted(predictions, key=lambda p: (p.event_time, p.prediction_id))
    records = [
        _score_one(p, outcome_provider, scored_at=scored_time, fit_window=window)
        for p in ordered
    ]
    scored = [r for r in records if r.scored]
    unscored_counts: dict[str, int] = {}
    for record in records:
        if not record.scored and record.unscored_reason is not None:
            unscored_counts[record.unscored_reason] = (
                unscored_counts.get(record.unscored_reason, 0) + 1
            )
    scored_by_key: dict[tuple[str, datetime, PredictionTarget], ScoredPrediction] = {}
    for record in scored:
        key = (record.instrument_id, record.event_time, record.target)
        if key in scored_by_key and baselines:
            raise ValueError(
                "duplicate scored (instrument, event_time, target) with "
                "baselines present: baseline matching would be ambiguous "
                f"for {key}"
            )
        scored_by_key[key] = record
    baseline_results = _score_baselines(
        scored_by_key,
        baselines or {},
        outcome_provider,
        scored_at=scored_time,
        fit_window=window,
    )
    metrics: list[TargetMetrics] = []
    for target in sorted({r.target for r in scored}, key=lambda t: t.value):
        group = [r for r in scored if r.target is target]
        arrays = _ScoredArrays(
            predicted=np.array([r.predicted for r in group], dtype=float),
            outcome=np.array(
                [r.outcome for r in group if r.outcome is not None], dtype=float
            ),
            error=np.array(
                [r.error for r in group if r.error is not None], dtype=float
            ),
        )
        metrics.append(
            _metrics_for_target(
                target,
                arrays,
                baselines=baseline_results.get(target, ()),
            )
        )
    return ShadowEvaluation(
        scored_at=scored_time,
        fit_window=window,
        predictions=tuple(records),
        metrics=tuple(metrics),
        n_total=len(records),
        n_scored=len(scored),
        n_unscored=len(records) - len(scored),
        unscored_counts=unscored_counts,
    )


def shadow_ledger_json(evaluation: ShadowEvaluation) -> str:
    """The scored-predictions ledger as deterministic JSON lines.

    One JSON object per prediction (scored or not), in the
    evaluation's deterministic order, keys sorted. Byte-identical
    for identical evaluations.
    """
    lines = [
        json.dumps(
            record.model_dump(mode="json"),
            sort_keys=True,
            separators=(",", ":"),
        )
        for record in evaluation.predictions
    ]
    return "\n".join(lines) + ("\n" if lines else "")
