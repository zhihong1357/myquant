"""Fetch the registered sample window for study credit-spread-dgs10-012.

Generated by the Stage 6c experiment assistant. Run after
preregistration, from the repo root:

    .venv/bin/python research/credit-spread-dgs10-012/fetch_data.py

The sample window comes from the registered spec: [train start,
holdout end). Raw response pages go to the gitignored cache under
data/cache/credit-spread-dgs10-012/raw/ (content-addressed RawStore); parsed
observations go to data/cache/credit-spread-dgs10-012/pit-1d/
(ParquetPITStore). Only the manifest (endpoints, parameters, date
ranges, payload SHA-256) and the panel summary (counts only, no raw
prices) are written into this research directory for commit. Raw
payloads and parquet never leave the local cache.

Each instrument's source is inferred from its catalog metadata key
(see SOURCE_METADATA_KEYS): an instrument with no known key — or
several — is refused, not guessed. Sources without an adapter fetch
helper (see TODO_SOURCES) fail fast before any fetch: implement the
marked fetcher first.

Adaptations beyond the generated skeleton (scaffold feedback — see the
study report):

- the SPX control leg (index:sp500, Yahoo ^GSPC) is fetched alongside
  the planner pair, with the Yahoo longName and positivity fail-fast
  checks from study 003/008; the Yahoo leg also drops bars whose
  close has not happened yet (a fetch run while the US market is
  open sees a partial bar for today, and the Observation contract
  refuses a close in the future) — see `_fetch_yahoo_finance`;
- the BAA decomposition leg is NOT fetched: v1 of the design
  assumed a daily FRED BAA series, but the fetch showed FRED
  publishes BAA monthly only (286 rows, 2003-01 to 2026-10). V2 of
  the design derives the daily BAA change from the identity
  ΔBAA = ΔBAA10Y + ΔDGS10 instead (see the design note);
- raw pages are stored with their real content type (text/csv for
  FRED, application/json for Yahoo) — the skeleton hard-coded
  application/json for every page;
- a FRED publication-lag verification (study 007's pattern) re-checks
  the preregistered lag behaviorally and records the observed last
  dates in the manifest; the fetch fails if the pattern is grossly
  inconsistent with the preregistration;
- the synchronized panel is built here (study 003's pattern) and its
  counts recorded in the manifest and the panel summary.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Callable
from dataclasses import dataclass
from dataclasses import replace as dataclass_replace
from datetime import UTC, date, datetime, time, timedelta
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

from myquant.adapters import fred as fred_adapter
from myquant.adapters import yahoo as yahoo_adapter
from myquant.catalog import MarketCatalog
from myquant.contracts import Observation
from myquant.hypotheses import HypothesisRegistry
from myquant.market import Instrument
from myquant.pit import ParquetPITStore
from myquant.quality import SeriesKey, inspect_observations
from myquant.raw import RawStore
from myquant.sources import SourceRegistry
from myquant.studies.panel import build_synchronized_panel

ROOT = Path(__file__).resolve().parent
REPO_ROOT = ROOT.parent.parent
CACHE_ROOT = REPO_ROOT / "data" / "cache" / "credit-spread-dgs10-012"

HYPOTHESIS_ID = "H0017"
SOURCE_IDS = ('fred', 'yahoo-finance')
INSTRUMENT_IDS = ('credit:baa-10y-spread', 'rates:us-10y-yield', 'index:sp500')
SOURCE_VERSION = 1
PIT_STORE_NAME = "pit-1d"

#: Venue recorded on observations, per source id.
SOURCE_VENUES = {'fred': 'fred', 'yahoo-finance': 'yahoo'}
#: Catalog metadata key holding the venue identifier, per source id.
SOURCE_METADATA_KEYS = {'fred': 'fred_series', 'yahoo-finance': 'yahoo_symbol'}
#: Raw-page content type, per source id.
SOURCE_CONTENT_TYPES = {
    'fred': 'text/csv',
    'yahoo-finance': 'application/json',
}
#: Sources with no implemented fetcher in this skeleton.
TODO_SOURCES = ()

#: Yahoo fail-fast identity check for the S&P 500 control leg.
SP500_SYMBOL = "^GSPC"
SP500_EXPECTED_LONG_NAME = "S&P 500"

US_EASTERN = ZoneInfo("America/New_York")

# The lag verification compares the last available FRED date against
# the most recent trading day (weekends stepped back; US holidays are
# not modelled — the check runs on a Thursday, far from any holiday).
LAG_CHECK_BAA10Y_SERIES = "BAA10Y"
LAG_CHECK_REFERENCE_SERIES = "DGS10"


@dataclass(frozen=True)
class _Page:
    """One raw response page kept for provenance."""

    url: str
    payload: bytes
    event_time: datetime | None


@dataclass(frozen=True)
class _FetchOutcome:
    """What one per-instrument fetch produced."""

    observations: list[Observation]
    pages: tuple[_Page, ...]
    endpoint: str
    items: int
    first_event: datetime | None
    last_event: datetime | None
    missing: int
    fields: tuple[str, ...]
    dropped_partial_bars: int = 0


def _venue_id(instrument: Instrument, source_id: str) -> str:
    """The venue identifier for an instrument, from its catalog metadata."""
    key = SOURCE_METADATA_KEYS[source_id]
    value = instrument.metadata.get(key)
    if not isinstance(value, str) or not value:
        raise ValueError(
            f"instrument {instrument.instrument_id} has no catalog metadata "
            f"key {key!r} for source {source_id!r}; fill the instrument stub"
        )
    return value


def _source_for_instrument(instrument: Instrument) -> str:
    """Infer an instrument's source from its catalog metadata keys.

    Exactly one known key must be present. None means the instrument
    stub is unfilled; several means the mapping is ambiguous. Both
    are refused — the scaffold never guesses which source an
    instrument comes from.
    """
    matches = [
        source_id
        for source_id, key in SOURCE_METADATA_KEYS.items()
        if instrument.metadata.get(key)
    ]
    if not matches:
        raise ValueError(
            f"instrument {instrument.instrument_id} has no known venue "
            f"metadata key (expected one of "
            f"{sorted(SOURCE_METADATA_KEYS.values())}); fill the stub"
        )
    if len(matches) > 1:
        raise ValueError(
            f"instrument {instrument.instrument_id} matches several sources "
            f"{sorted(matches)}; leave exactly one venue metadata key"
        )
    return matches[0]


def _fetch_fred(
    instrument: Instrument,
    *,
    start: datetime,
    end: datetime,
    fetched_at: datetime,
) -> _FetchOutcome:
    """Fetch one FRED series as dated daily values."""
    series_id = _venue_id(instrument, "fred")
    unit = instrument.quote_currency
    if unit is None:
        raise ValueError(
            f"instrument {instrument.instrument_id} has no quote_currency; "
            "fill the instrument stub"
        )
    series = fred_adapter.fetch_series(
        series_id, start=start.date(), end=end.date()
    )
    # FRED values sit at 21:00 UTC on their date, so the inclusive
    # end date can land past the window end; keep only [start, end).
    observations = [
        observation
        for observation in fred_adapter.series_to_observations(
            series,
            instrument_id=instrument.instrument_id,
            venue="fred",
            source_id="fred",
            source_version=SOURCE_VERSION,
            ingested_at=fetched_at,
            unit=unit,
        )
        if start <= observation.event_time < end
    ]
    return _FetchOutcome(
        observations=observations,
        pages=(
            _Page(
                url=series.url,
                payload=series.payload,
                event_time=observations[-1].event_time
                if observations
                else None,
            ),
        ),
        endpoint="https://fred.stlouisfed.org/graph/fredgraph.csv",
        items=len(series.observations),
        first_event=observations[0].event_time if observations else None,
        last_event=observations[-1].event_time if observations else None,
        missing=series.missing_count,
        fields=("close",),
    )


def _fetch_yahoo_finance(
    instrument: Instrument,
    *,
    start: datetime,
    end: datetime,
    fetched_at: datetime,
) -> _FetchOutcome:
    """Fetch daily Yahoo bars for one instrument."""
    symbol = _venue_id(instrument, "yahoo-finance")
    unit = instrument.quote_currency
    if unit is None:
        raise ValueError(
            f"instrument {instrument.instrument_id} has no quote_currency; "
            "fill the instrument stub"
        )
    chart = yahoo_adapter.fetch_chart(
        symbol, start=start.date(), end=end.date()
    )
    # Drop bars whose close has not happened yet: when the fetch runs
    # while the US market is open, Yahoo returns a partial bar for
    # today, and its 21:00 UTC close is after the fetch time, so the
    # Observation contract (ingested_at cannot precede available_at)
    # refuses it. A daily bar is only an observation once its close
    # has happened; the partial bar is excluded here (the raw payload
    # is still stored whole, so the exclusion is auditable) and
    # counted in the manifest. The [start, end) filter below would
    # have excluded it anyway — this pre-filter exists because the
    # conversion itself refuses a future close.
    complete_bars = tuple(
        bar
        for bar in chart.bars
        if datetime.combine(
            bar.trading_date, yahoo_adapter.DAILY_CLOSE_UTC, tzinfo=UTC
        )
        <= fetched_at
    )
    dropped_partial_bars = len(chart.bars) - len(complete_bars)
    if dropped_partial_bars:
        chart = dataclass_replace(chart, bars=complete_bars)
    # Fail-fast checks (the ^MOVE lesson, study 003): refuse to guess
    # the instrument, and refuse non-positive closes (log returns need
    # positive levels). The generated skeleton had neither check.
    if symbol == SP500_SYMBOL and chart.long_name != SP500_EXPECTED_LONG_NAME:
        raise ValueError(
            f"Yahoo {symbol!r}: meta longName is {chart.long_name!r}, "
            f"expected {SP500_EXPECTED_LONG_NAME!r}; refusing to guess "
            "the instrument"
        )
    if any(bar.close <= 0 for bar in chart.bars):
        raise ValueError(f"Yahoo {symbol!r}: non-positive close found")
    # Yahoo bars sit at 21:00 UTC on their date, so the inclusive
    # end date can land past the window end; keep only [start, end).
    observations = [
        observation
        for observation in yahoo_adapter.chart_to_observations(
            chart,
            instrument_id=instrument.instrument_id,
            venue="yahoo",
            source_id="yahoo-finance",
            source_version=SOURCE_VERSION,
            ingested_at=fetched_at,
            unit=unit,
        )
        if start <= observation.event_time < end
    ]
    return _FetchOutcome(
        observations=observations,
        pages=(
            _Page(
                url=chart.url,
                payload=chart.payload,
                event_time=observations[-1].event_time
                if observations
                else None,
            ),
        ),
        endpoint="https://query2.finance.yahoo.com/v8/finance/chart",
        items=len(chart.bars),
        first_event=observations[0].event_time if observations else None,
        last_event=observations[-1].event_time if observations else None,
        missing=chart.missing_count,
        fields=("close",),
        dropped_partial_bars=dropped_partial_bars,
    )


FETCHERS: dict[str, Callable[..., _FetchOutcome]] = {
    "fred": _fetch_fred,
    "yahoo-finance": _fetch_yahoo_finance,
}


def _fetch_one(
    instrument_id: str,
    start: datetime,
    end: datetime,
    *,
    catalog: MarketCatalog,
    raw_store: RawStore,
    pit_store: ParquetPITStore,
    fetched_at: datetime,
) -> dict[str, Any]:
    instrument = catalog.get_instrument(instrument_id, version=1)
    source_id = _source_for_instrument(instrument)
    if source_id not in SOURCE_IDS:
        raise ValueError(
            f"instrument {instrument_id} maps to source {source_id!r}, "
            f"which is not in the study sources {sorted(SOURCE_IDS)}"
        )
    outcome = FETCHERS[source_id](
        instrument, start=start, end=end, fetched_at=fetched_at
    )
    page_entries: list[dict[str, str]] = []
    for page in outcome.pages:
        record = raw_store.put(
            page.payload,
            source_id=source_id,
            available_at=fetched_at,
            content_type=SOURCE_CONTENT_TYPES[source_id],
            source_version=SOURCE_VERSION,
            event_time=page.event_time,
            ingested_at=fetched_at,
        )
        page_entries.append(
            {
                "url": page.url,
                "payload_sha256": record.payload_sha256,
                "record_id": record.record_id,
            }
        )
    parquet_path = pit_store.write_batch(outcome.observations)
    return {
        "instrument_id": instrument_id,
        "source_id": source_id,
        "venue": SOURCE_VENUES[source_id],
        "venue_id": _venue_id(instrument, source_id),
        "endpoint": outcome.endpoint,
        "window_start": start.isoformat(),
        "window_end": end.isoformat(),
        "items": outcome.items,
        "first_event": (
            outcome.first_event.isoformat() if outcome.first_event else None
        ),
        "last_event": (
            outcome.last_event.isoformat() if outcome.last_event else None
        ),
        "missing": outcome.missing,
        "dropped_partial_bars": outcome.dropped_partial_bars,
        "fields": list(outcome.fields),
        "pages": page_entries,
        "pit_store": PIT_STORE_NAME,
        "pit_parquet": parquet_path.name,
        "pit_parquet_sha256": parquet_path.stem,
        "observation_rows": len(outcome.observations),
    }


def _previous_trading_day(day: date) -> date:
    """The most recent weekday on or before ``day``."""
    current = day
    while current.weekday() >= 5:
        current -= timedelta(days=1)
    return current


def _most_recent_trading_day(fetched_at: datetime) -> date:
    """The latest trading day whose 16:00 ET close precedes the fetch.

    Study 007's check ran before the US open, so it stepped back a
    day unconditionally. This fetch runs after the close, so a weekday
    fetch after 16:00 ET counts today: the market has closed and the
    day's values exist (FRED posts the next morning). US holidays are
    not modelled — the check runs on a Thursday, far from any holiday.
    """
    now_us = fetched_at.astimezone(US_EASTERN)
    today_us = now_us.date()
    if today_us.weekday() < 5 and now_us.time() >= time(16, 0):
        return today_us
    return _previous_trading_day(today_us - timedelta(days=1))


def check_fred_lag(
    *,
    raw_store: RawStore,
    fetched_at: datetime,
) -> dict[str, Any]:
    """Re-verify the FRED publication lag with unbounded fetches.

    The preregistration's lag rule: a standard FRED daily value dated
    t posts on the next business day (study 007, N=1), and BAA10Y
    posts about a day later than that (6b evidence probe
    2026-11-18T21:45Z: BAA10Y latest 2026-11-16 while VIXCLS/VXNCLS/
    DGS10 were already 2026-11-17), so BAA10Y's effective availability
    lag is 2 trading days.

    This check re-records the last available date for BAA10Y and
    DGS10 at fetch time. DGS10 must be the most recent trading day
    or the trading day before it (study 007's rule — either is
    consistent with next-business-day posting, depending on whether
    the fetch ran before or after the morning posting). BAA10Y must
    be at most one trading day behind DGS10 and never ahead of it:
    one day behind means the extra-day lag is visible right now; level
    with DGS10 means BAA10Y posted after the close (the 6b probe,
    taken 45 minutes after the close, already showed it unposted at
    that time), which is still an effective 2-trading-day lag for
    close-of-day decisions. Anything else falsifies the preregistered
    lag and fails the fetch. The check payloads are raw-stored but NOT
    written to PIT (they would duplicate the bounded series).
    """
    today_us = fetched_at.astimezone(US_EASTERN).date()
    most_recent = _most_recent_trading_day(fetched_at)
    previous = _previous_trading_day(most_recent - timedelta(days=1))
    entries: dict[str, dict[str, Any]] = {}
    for series_id in (LAG_CHECK_BAA10Y_SERIES, LAG_CHECK_REFERENCE_SERIES):
        series = fred_adapter.fetch_series(series_id)
        last_date = series.observations[-1][0]
        record = raw_store.put(
            series.payload,
            source_id="fred",
            available_at=fetched_at,
            content_type="text/csv",
            source_version=SOURCE_VERSION,
            event_time=datetime.combine(
                last_date, fred_adapter.DAILY_CLOSE_UTC, tzinfo=UTC
            ),
            ingested_at=fetched_at,
        )
        entries[series_id] = {
            "last_available_date": last_date.isoformat(),
            "rows": len(series.observations),
            "endpoint": series.url,
            "payload_sha256": record.payload_sha256,
            "record_id": record.record_id,
        }
    dgs10_last = date.fromisoformat(
        entries[LAG_CHECK_REFERENCE_SERIES]["last_available_date"]
    )
    baa_last = date.fromisoformat(
        entries[LAG_CHECK_BAA10Y_SERIES]["last_available_date"]
    )
    if dgs10_last not in (most_recent, previous):
        raise ValueError(
            f"FRED lag re-check failed for {LAG_CHECK_REFERENCE_SERIES}: "
            f"last available date is {dgs10_last}, expected {most_recent} "
            f"or {previous} (N=1 posting); the preregistered lag no "
            "longer holds"
        )
    baa_one_behind = _previous_trading_day(dgs10_last - timedelta(days=1))
    if baa_last not in (dgs10_last, baa_one_behind):
        raise ValueError(
            f"FRED lag re-check failed for {LAG_CHECK_BAA10Y_SERIES}: "
            f"last available date is {baa_last}, expected {dgs10_last} "
            f"(posted after the close) or {baa_one_behind} (one trading "
            "day behind the reference series); the preregistered "
            "2-trading-day BAA10Y lag no longer holds"
        )
    if baa_last == dgs10_last:
        interpretation = (
            "BAA10Y is level with the reference series at fetch time; "
            "the 6b probe (2026-11-18T21:45Z, 45 minutes after the US "
            "close) showed it one trading day behind at that time, so "
            "the posting happened after the close and the effective "
            "2-trading-day lag for close-of-day decisions stands."
        )
    else:
        interpretation = (
            "BAA10Y is one trading day behind the reference series at "
            "fetch time, reproducing the 6b probe's extra-day lag; the "
            "effective 2-trading-day lag for close-of-day decisions "
            "stands."
        )
    return {
        "fetched_at": fetched_at.isoformat(),
        "today_us_eastern": today_us.isoformat(),
        "most_recent_trading_day": most_recent.isoformat(),
        "previous_trading_day": previous.isoformat(),
        "consistent_with_baa10y_lag_steps": 2,
        "consistent_with_reference_lag_steps": 1,
        "series": entries,
        "interpretation": interpretation,
    }


def main() -> None:
    if TODO_SOURCES:
        raise NotImplementedError(
            "TODO: these sources have no implemented fetcher in this "
            f"skeleton: {sorted(TODO_SOURCES)}. Implement the marked "
            "fetch functions before fetching."
        )
    registry = HypothesisRegistry(ROOT / "hypotheses")
    # The trial binds H0017 v2 (the pre-trial amendment dropping the
    # BAA fetch leg); the windows are identical in v1 and v2.
    spec = registry.get(HYPOTHESIS_ID, version=2).spec
    start = spec.train_window.start
    end = spec.holdout_window.end
    if end <= start:
        raise ValueError("registered sample window is empty")

    fetched_at = datetime.now(UTC)
    raw_store = RawStore(CACHE_ROOT / "raw")
    source_registry = SourceRegistry(ROOT / "sources")
    for source_id in SOURCE_IDS:
        source_registry.require_research_permission(
            source_id, version=SOURCE_VERSION
        )
    pit_store = ParquetPITStore(CACHE_ROOT / PIT_STORE_NAME, source_registry)
    catalog = MarketCatalog(ROOT / "catalog")

    fetches: list[dict[str, Any]] = []
    for instrument_id in INSTRUMENT_IDS:
        entry = _fetch_one(
            instrument_id,
            start,
            end,
            catalog=catalog,
            raw_store=raw_store,
            pit_store=pit_store,
            fetched_at=fetched_at,
        )
        fetches.append(entry)
        print(
            f"{instrument_id} ({entry['source_id']}): {entry['items']} items, "
            f"{entry['observation_rows']} observations, "
            f"{entry['missing']} missing, {len(entry['pages'])} pages"
        )

    observations = pit_store.query_as_of(fetched_at)
    expected_series: set[SeriesKey] = {
        (
            entry["instrument_id"],
            entry["venue"],
            field,
            entry["source_id"],
            SOURCE_VERSION,
        )
        for entry in fetches
        for field in entry["fields"]
    }
    report = inspect_observations(
        observations, expected_series=expected_series
    )
    quality = {
        "row_count": report.row_count,
        "unique_series_count": report.unique_series_count,
        "unique_instrument_count": report.unique_instrument_count,
        "event_time_min": (
            report.event_time_min.isoformat() if report.event_time_min else None
        ),
        "event_time_max": (
            report.event_time_max.isoformat() if report.event_time_max else None
        ),
        "missing_expected_series": list(report.missing_expected_series),
        "issues": [
            {
                "code": issue.code,
                "severity": issue.severity.value,
                "message": issue.message,
                "count": issue.count,
            }
            for issue in report.issues
        ],
    }
    lag_check = check_fred_lag(raw_store=raw_store, fetched_at=fetched_at)
    print(
        "FRED lag re-check: "
        + ", ".join(
            f"{series_id} last available "
            f"{entry['last_available_date']}"
            for series_id, entry in lag_check["series"].items()
        )
        + f" (most recent trading day {lag_check['most_recent_trading_day']}); "
        "consistent with a 2-trading-day BAA10Y lag"
    )

    # Synchronized daily panel (no bar_seconds: US trading days have
    # weekend gaps, so returns are per-trading-day log returns).
    # The publication lag is applied in the trial, not here: this
    # panel is the unlagged synchronized base the trial builds on.
    panel = build_synchronized_panel(
        observations,
        instruments=INSTRUMENT_IDS,
        field="close",
    )
    panel_info = {
        "instruments": list(INSTRUMENT_IDS),
        "close_rows": int(panel.closes.shape[0]),
        "return_rows": panel.row_count,
        "dropped_close_rows": panel.dropped_close_rows,
        "dropped_return_rows": panel.dropped_return_rows,
        "first_return_time": panel.first_time.isoformat(),
        "last_return_time": panel.last_time.isoformat(),
    }
    print(
        f"panel: {panel.row_count} return rows, "
        f"{panel.dropped_close_rows} dropped close rows, "
        f"{panel.dropped_return_rows} dropped return rows"
    )

    manifest = {
        "study": "credit-spread-dgs10-012",
        "fetched_at": fetched_at.isoformat(),
        "cache_root": "data/cache/credit-spread-dgs10-012",
        "source_ids": list(SOURCE_IDS),
        "source_version": SOURCE_VERSION,
        "fetches": fetches,
        "fred_lag_check": lag_check,
        "panel": panel_info,
        "quality": quality,
    }
    manifest_bytes = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    manifest_path = ROOT / "manifest.json"
    manifest_path.write_bytes(manifest_bytes)
    print(f"manifest written: {manifest_path}")
    print(f"manifest sha256: {hashlib.sha256(manifest_bytes).hexdigest()}")
    summary = {
        "study": "credit-spread-dgs10-012",
        "fetched_at": fetched_at.isoformat(),
        "panels": [
            {
                "instrument_id": entry["instrument_id"],
                "source_id": entry["source_id"],
                "items": entry["items"],
                "observation_rows": entry["observation_rows"],
                "missing": entry["missing"],
                "first_event": entry["first_event"],
                "last_event": entry["last_event"],
            }
            for entry in fetches
        ],
        "fred_lag_check": lag_check,
        "panel": panel_info,
        "quality_row_count": quality["row_count"],
        "quality_issues": quality["issues"],
    }
    summary_path = ROOT / "panel-summary.json"
    summary_path.write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"panel summary written: {summary_path}")


if __name__ == "__main__":
    main()
